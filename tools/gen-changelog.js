#!/usr/bin/env node
/**
 * Generates CHANGELOG.md from the in-app changelog in project-tracker.html.
 *
 * The app holds the authoritative history in a JavaScript array. Maintaining
 * a second copy by hand guarantees they drift, so this derives the markdown
 * from the source of truth instead.
 *
 *   node tools\gen-changelog.js              # writes CHANGELOG.md
 *   node tools\gen-changelog.js --check      # fails if out of date (for CI)
 *   node tools\gen-changelog.js --stdout     # print, write nothing
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const appFile = path.join(root, 'project-tracker.html');
const outFile = path.join(root, 'CHANGELOG.md');

if (!fs.existsSync(appFile)) {
  console.error('Not found: ' + appFile);
  process.exit(1);
}
const src = fs.readFileSync(appFile, 'utf8');

/* Find the array literal containing the changelog. The variable name is not
   assumed - we locate the first `major:` key and walk outwards to the
   enclosing `[`, then bracket-match to its close. */
function extractChangelogArray(text) {
  const anchor = text.indexOf('major:');
  if (anchor < 0) throw new Error('No changelog data found (no "major:" key).');

  // Walk back to the opening bracket of the array that holds this object.
  let depth = 0, start = -1;
  for (let i = anchor; i >= 0; i--) {
    const c = text[i];
    if (c === ']' || c === '}') depth++;
    else if (c === '}') depth--;
    else if (c === '[') {
      if (depth === 0) { start = i; break; }
      depth--;
    } else if (c === '{') {
      if (depth > 0) depth--;
    }
  }
  if (start < 0) throw new Error('Could not find the start of the changelog array.');

  // Bracket-match forwards, ignoring brackets inside strings.
  let d = 0, inStr = null, esc = false;
  for (let i = start; i < text.length; i++) {
    const c = text[i];
    if (esc) { esc = false; continue; }
    if (inStr) {
      if (c === '\\') esc = true;
      else if (c === inStr) inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') { inStr = c; continue; }
    if (c === '[') d++;
    else if (c === ']') { d--; if (d === 0) return text.slice(start, i + 1); }
  }
  throw new Error('Unbalanced brackets in the changelog array.');
}

let literal;
try {
  literal = extractChangelogArray(src);
} catch (e) {
  console.error(e.message);
  process.exit(1);
}
let data;
try {
  data = vm.runInNewContext('(' + literal + ')', Object.create(null), { timeout: 2000 });
} catch (e) {
  console.error('Could not parse the changelog array: ' + e.message);
  process.exit(1);
}
if (!Array.isArray(data)) {
  console.error('Changelog data is not an array.');
  process.exit(1);
}

const appVersion = (src.match(/const APP_VERSION\s*=\s*"([\d.]+)"/) || [])[1] || '';

/* ---------------- render ---------------- */
const TAG_LABEL = {
  feature: 'Features',
  fixes: 'Fixes',
  performance: 'Performance',
  interface: 'Interface',
  storage: 'Storage',
  current: '',
  ''      : ''
};

const lines = [];
lines.push('# Changelog');
lines.push('');
lines.push('Generated from the in-app changelog in `project-tracker.html`, which is the');
lines.push('authoritative history. Do not edit this file by hand - run:');
lines.push('');
lines.push('```powershell');
lines.push('node tools\\gen-changelog.js');
lines.push('```');
lines.push('');
if (appVersion) {
  lines.push('Current version: **v' + appVersion + '**');
  lines.push('');
}

let releaseCount = 0;
for (const group of data) {
  const major = group.major || group.name || '';
  if (major) {
    lines.push('---');
    lines.push('');
    lines.push('## ' + major + (group.tag === 'current' ? ' (current)' : ''));
    lines.push('');
  }
  const releases = group.releases || group.items || [];
  for (const rel of releases) {
    releaseCount++;
    const v = rel.v || rel.version || '';
    const label = TAG_LABEL[rel.tag] !== undefined ? TAG_LABEL[rel.tag] : rel.tag;
    lines.push('### v' + v + (label ? ' - ' + label : ''));
    lines.push('');
    for (const item of (rel.items || [])) {
      // Unwrap simple inline HTML the app renders but markdown does not need.
      const clean = String(item)
        .replace(/<\/?b>/g, '**')
        .replace(/<br\s*\/?>/g, ' ')
        .replace(/&amp;/g, '&')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/\s+/g, ' ')
        .trim();
      lines.push('- ' + clean);
    }
    lines.push('');
  }
}

const md = lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';

if (process.argv.includes('--stdout')) {
  process.stdout.write(md);
  process.exit(0);
}

if (process.argv.includes('--check')) {
  const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (existing !== md) {
    console.error('CHANGELOG.md is out of date. Run: node tools\\gen-changelog.js');
    process.exit(1);
  }
  console.log('CHANGELOG.md is up to date (' + releaseCount + ' releases).');
  process.exit(0);
}

fs.writeFileSync(outFile, md, 'utf8');
console.log('Wrote CHANGELOG.md - ' + releaseCount + ' releases across ' + data.length + ' version group(s).');
